const int maxn = 2e5 + 5;

vector<int> adj[maxn];

vector<int> ans;

void dfs(int node, int par, int &target, vector<int> &path) {

	path.push_back(node);

	if(node == target) {
		ans = path;
		return;
	}

	for(int next: adj[node]) {
		if(next == par)
			continue;

		dfs(next, node, target, path);
	}

	path.pop_back();


}
